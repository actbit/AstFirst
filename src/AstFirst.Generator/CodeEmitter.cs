using System.Collections.Generic;
using System.Text;
using AstFirst.Core.Lexing;

namespace AstFirst.Generator;

/// <summary>
/// GrammarModel からレクサ/パーサの C# コードを生成する。
/// 生成コードは Core (Dfa/Lexer/LalrTable 等) に依存する。
/// </summary>
public static class CodeEmitter
{
    /// <summary>レクサの C# コードを生成。DFA を static 配列に直列化し Lexer を駆動。</summary>
    public static string EmitLexer(GrammarModel model, Dfa dfa, IReadOnlyList<LexerRule> rules, string className, string ns)
    {
        var boundaries = dfa.Alphabet.Boundaries;
        int stateCount = dfa.States.Count;
        int classCount = dfa.Alphabet.ClassCount;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using AstFirst.Core.Lexing;");
        sb.AppendLine();
        if (ns.Length > 0) { sb.AppendLine("namespace " + ns + ";"); sb.AppendLine(); }
        sb.AppendLine("public static class " + className);
        sb.AppendLine("{");

        // Boundaries
        sb.Append("    public static readonly int[] Boundaries = new int[] { ");
        for (int i = 0; i < boundaries.Count; i++) { if (i > 0) sb.Append(", "); sb.Append(boundaries[i]); }
        sb.AppendLine(" };");

        // Transitions[state][class]: ジャグ配列 (各状態の遷移が1次元配列)。
        // 2次元配列 (int[,]) よりアクセスが速く、Lexer が static 配列を直接参照する。
        sb.Append("    public static readonly int[][] Transitions = new int[").Append(stateCount).AppendLine("][]");
        sb.AppendLine("    {");
        for (int s = 0; s < stateCount; s++)
        {
            sb.Append("        new int[] { ");
            var tr = dfa.States[s].Transitions;
            for (int c = 0; c < classCount; c++) { if (c > 0) sb.Append(", "); sb.Append(tr[c]); }
            sb.Append(" }");
            sb.AppendLine(s < stateCount - 1 ? "," : "");
        }
        sb.AppendLine("    };");

        // AcceptTokenIds[state]: 0 = 非受理
        sb.Append("    public static readonly int[] AcceptTokenIds = new int[] { ");
        for (int s = 0; s < stateCount; s++)
        {
            if (s > 0) sb.Append(", ");
            sb.Append(dfa.States[s].IsAccept ? dfa.States[s].AcceptTokenId : 0);
        }
        sb.AppendLine(" };");

        // Alphabet: アルファベット分割 (1回だけ構築してキャッシュ)。
        sb.AppendLine("    public static readonly AlphabetPartition Alphabet = AlphabetPartition.FromBoundaries(Boundaries);");

        // Rules: 字句規則 (1回だけ構築してキャッシュ)。
        sb.Append("    public static readonly LexerRule[] Rules = new LexerRule[] {");
        for (int i = 0; i < rules.Count; i++)
        {
            var r = rules[i];
            sb.AppendLine();
            sb.Append("        new LexerRule(\"").Append(EscapeStringLiteral(r.Pattern)).Append("\", ")
              .Append(r.TokenId).Append(", ").Append(r.Priority).Append(", ").Append(r.IsHidden ? "true" : "false").Append("),");
        }
        sb.AppendLine();
        sb.AppendLine("    };");

        // Tokenize: static 配列 (Transitions/AcceptTokenIds) とキャッシュ済みの Alphabet/Rules を
        // 直接 Lexer.Tokenize に渡す。Dfa/DfaState オブジェクトの毎回の構築・コピーを回避する。
        sb.AppendLine("    /// <summary>Tokenizes the input into a list of tokens.</summary>");
        sb.AppendLine("    /// <remarks>入力をトークン列に分割します (DFA テーブルは static 配列を直接参照)。</remarks>");
        sb.AppendLine("    public static List<LexToken> Tokenize(string input)");
        sb.AppendLine("        => Lexer.Tokenize(Transitions, AcceptTokenIds, Alphabet, 0, Rules, input);");
        sb.AppendLine("}");

        return sb.ToString();
    }

    public static (string ns, string type) SplitFullName(string fullName)
    {
        int i = fullName.LastIndexOf('.');
        return i < 0 ? ("", fullName) : (fullName.Substring(0, i), fullName.Substring(i + 1));
    }

    /// <summary>[Grammar(Mode=...)] の値を生成型名用の suffix に変換する。</summary>
    /// <remarks>通常の識別子は従来の名前を維持し、記号や空白を含む値は衝突しない hash を付ける。</remarks>
    public static string ModeSuffix(string? mode)
    {
        if (string.IsNullOrEmpty(mode)) return "";
        var modeText = mode!;

        var sanitized = new StringBuilder(modeText.Length + 1);
        for (int i = 0; i < modeText.Length; i++)
        {
            char c = modeText[i];
            if (i == 0 && char.IsDigit(c)) sanitized.Append('_');
            sanitized.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        }

        var safe = sanitized.ToString();
        if (safe == modeText) return "_" + safe;

        uint hash = 2166136261;
        unchecked
        {
            for (int i = 0; i < modeText.Length; i++) hash = (hash ^ modeText[i]) * 16777619;
        }
        return "_" + safe + "_" + hash.ToString("x8");
    }

    /// <summary>[Rule] 引数名 (lowerCamel) をプロパティ名 (PascalCase) に。空なら "Item"。</summary>
    public static string Pascalize(string? s)
        => string.IsNullOrEmpty(s) ? "Item" : char.ToUpperInvariant(s![0]) + s.Substring(1);

    /// <summary>生成ノードのメンバー名として安全な、引数由来のプロパティ名を返す。</summary>
    /// <remarks>C# では型と同名のメンバーを宣言できないため、衝突時は末尾に '_' を付ける。</remarks>
    public static string PropertyName(string nodeFullName, string? parameterName)
    {
        var propertyName = Pascalize(parameterName);
        var (_, nodeName) = SplitFullName(nodeFullName);
        return propertyName == nodeName ? propertyName + "_" : propertyName;
    }

    /// <summary>ノード内で生成する全パラメータプロパティの名前を決定する。</summary>
    /// <remarks>型・生成メンバーとの衝突と、異なる引数名の PascalCase 衝突を避ける。</remarks>
    public static IReadOnlyDictionary<string, string> GetPropertyNames(
        string nodeFullName, IReadOnlyList<RuleModel> rules, IReadOnlyList<string>? reservedMemberNames = null,
        IReadOnlyList<ChildModel>? inheritedChildren = null)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        var used = new HashSet<string>(StringComparer.Ordinal)
        {
            "Span", "AcceptState", "IsAccepted", "NotifyAccepted",
            "OnReduce", "OnAccepted"
        };
        var (_, nodeName) = SplitFullName(nodeFullName);
        used.Add(nodeName);
        if (rules.Count > 0) used.Add("RuleName");
        foreach (var rule in rules)
            used.Add(rule.MethodName);
        if (reservedMemberNames is not null)
            foreach (var memberName in reservedMemberNames)
                used.Add(memberName);

        var inheritedByName = new Dictionary<string, string>(StringComparer.Ordinal);
        if (inheritedChildren is not null)
            foreach (var child in inheritedChildren)
            {
                inheritedByName[child.PropertyName] = child.TypeFullName;
                used.Add(child.PropertyName);
            }
        var reusedInherited = new HashSet<string>(StringComparer.Ordinal);
        var grouped = new Dictionary<string, string>(StringComparer.Ordinal);

        for (int ruleIndex = 0; ruleIndex < rules.Count; ruleIndex++)
        {
            var rule = rules[ruleIndex];
            for (int parameterIndex = 0; parameterIndex < rule.Parameters.Count; parameterIndex++)
            {
                var parameter = rule.Parameters[parameterIndex];
                if (parameter.IsContext || parameter.Name is null) continue;

                var baseName = PropertyName(nodeFullName, parameter.Name);
                var groupKey = ParameterGroupKey(parameter);
                if (!grouped.TryGetValue(groupKey, out var name))
                {
                    if (inheritedByName.TryGetValue(baseName, out var inheritedType)
                        && inheritedType == ConstructorType(parameter)
                        && reusedInherited.Add(baseName))
                    {
                        name = baseName;
                    }
                    else
                    {
                        name = baseName;
                        while (!used.Add(name)) name += "_";
                    }
                    grouped[groupKey] = name;
                }
                names[PropertyKey(rule, parameterIndex)] = name;
            }
        }

        return names;
    }

    /// <summary>Returns the generated-property lookup key for one rule parameter.</summary>
    public static string PropertyKey(RuleModel rule, int parameterIndex)
        => RuleKey(rule) + "\0" + parameterIndex;

    private static string ParameterGroupKey(ParamModel parameter)
        => (parameter.Name ?? "") + "\0" + ConstructorType(parameter);

    private static string RuleKey(RuleModel rule)
    {
        var sb = new StringBuilder(rule.MethodName.Length + 32);
        sb.Append(rule.MethodName).Append('\0');
        foreach (var parameter in rule.Parameters)
            sb.Append(ConstructorType(parameter)).Append('\0');
        return sb.ToString();
    }

    private static string ConstructorType(ParamModel parameter) => parameter.IsRepeat
        ? "System.Collections.Generic.IReadOnlyList<" + parameter.TypeFullName + ">"
        : parameter.TypeFullName;

    /// <summary>Escapes a value for a regular C# string literal.</summary>
    public static string EscapeStringLiteral(string s)
    {
        var escaped = new StringBuilder(s.Length + 8);
        foreach (var c in s)
        {
            switch (c)
            {
                case '\\': escaped.Append("\\\\"); break;
                case '"': escaped.Append("\\\""); break;
                case '\r': escaped.Append("\\r"); break;
                case '\n': escaped.Append("\\n"); break;
                case '\t': escaped.Append("\\t"); break;
                case '\0': escaped.Append("\\0"); break;
                default:
                    if (char.IsControl(c)) escaped.Append("\\u").Append(((int)c).ToString("x4"));
                    else escaped.Append(c);
                    break;
            }
        }
        return escaped.ToString();
    }
}
